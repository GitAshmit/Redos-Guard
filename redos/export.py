"""C header export for the ESP32: a minimized-DFA table and Thompson-NFA tables for the
backtracking matcher. Usage:  python -m redos.export "(a+)+" > redos_tables.h
"""
import sys

from .dfa import alphabet_classes, build_dfa, minimize
from .nfa import build_nfa, remove_epsilon
from .parser import RegexSyntaxError, parse

MAX_CLASSES = 64


def _array(ctype, name, values, per_line=16):
    values = list(values) or [0]
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("  " + ", ".join(str(v) for v in values[i : i + per_line]))
    return f"static const {ctype} {name}[{len(values)}] = {{\n" + ",\n".join(lines) + "\n};\n"


def _table(ctype, name, rows):
    body = ",\n".join("  {" + ", ".join(str(v) for v in row) + "}" for row in rows)
    return f"static const {ctype} {name}[{len(rows)}][{len(rows[0])}] = {{\n{body}\n}};\n"


def to_c_header(pattern):
    ast = parse(pattern)
    nfa = build_nfa(ast)
    efn = remove_epsilon(nfa)
    classes = alphabet_classes(m for _, m, _ in nfa.edges)
    if len(classes) > MAX_CLASSES:
        raise RegexSyntaxError(f"too many character classes for the ESP32 export ({len(classes)} > {MAX_CLASSES})")
    dfa = minimize(build_dfa(efn, classes))
    k = len(classes)

    char_dst = [-1] * nfa.n
    char_set = [0] * nfa.n
    for src, mask, dst in nfa.edges:
        char_dst[src] = dst
        char_set[src] = sum(1 << ci for ci, c in enumerate(classes) if c & mask)
    eps_off, eps = [0], []
    for s in range(nfa.n):
        eps.extend(nfa.eps[s])
        eps_off.append(len(eps))

    safe_name = pattern.encode("unicode_escape").decode().replace("*/", "* /")
    out = [
        "// Generated by ReDoS Guard. Do not edit by hand.",
        f"// Regex: {safe_name}",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define RG_NCLASS {k}",
        f"#define RG_DFA_STATES {dfa.n}",
        f"#define RG_DFA_START 0",
        f"#define RG_NFA_STATES {nfa.n}",
        f"#define RG_NFA_START {nfa.start}",
        f"#define RG_NFA_ACCEPT {nfa.accept}",
        "",
        "// character -> class (RG_NCLASS = outside the supported alphabet)",
        _array("uint8_t", "RG_CLASS_MAP", dfa.cmap, 16),
        f"// minimized DFA: RG_DFA_TRANS[state][class], {k + 1} columns",
        _table("uint16_t", "RG_DFA_TRANS", dfa.trans),
        _array("uint8_t", "RG_DFA_ACCEPT", [1 if s in dfa.accept else 0 for s in range(dfa.n)], 32),
        "// Thompson NFA for the backtracking matcher: one optional character edge per state",
        _array("int16_t", "RG_NFA_CHAR_DST", char_dst, 16),
        _array("uint64_t", "RG_NFA_CHAR_SET", [f"0x{v:x}ULL" for v in char_set], 4),
        _array("uint16_t", "RG_NFA_EPS_OFF", eps_off, 16),
        _array("uint16_t", "RG_NFA_EPS", eps, 16),
    ]
    return "\n".join(out)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit('usage: python -m redos.export "<regex>" > redos_tables.h')
    try:
        print(to_c_header(sys.argv[1]))
    except RegexSyntaxError as e:
        sys.exit(f"error: {e.msg}" + (f" at position {e.pos}" if e.pos is not None else ""))
